#!/usr/bin/env bash
# Builds and signs the Qudelix Widget APK without Gradle.
set -euo pipefail
cd "$(dirname "$0")"

SDK="${ANDROID_SDK:-$HOME/android-sdk}"
BT="$SDK/build-tools/34.0.0"
JAR="$SDK/platforms/android-34/android.jar"
JDK="$SDK/jdk"
AAPT2="$BT/aapt2"; D8="$BT/d8"; ZIPALIGN="$BT/zipalign"; APKSIGNER="$BT/apksigner"
JAVAC="$JDK/bin/javac"
export JAVA_HOME="$JDK"
export PATH="$JDK/bin:$PATH"

OUT=build
# Machine-specific values (update server) — optional; see ../local.env.example.
[[ -f ../local.env ]] && source ../local.env
# Semantic version shared with the Windows widget: ../VERSION (MAJOR.MINOR.PATCH).
# versionCode is derived so it always grows: MAJOR*1000000 + MINOR*1000 + PATCH.
VERSION_NAME="$(tr -d '[:space:]' < ../VERSION)"
IFS=. read -r V_MAJ V_MIN V_PAT <<< "$VERSION_NAME"
VERSION_CODE=$(( V_MAJ * 1000000 + V_MIN * 1000 + V_PAT ))
rm -rf "$OUT"; mkdir -p "$OUT/gen" "$OUT/classes" "$OUT/dex" "$OUT/res"

echo "[1/6] aapt2 compile resources"
"$AAPT2" compile --dir res -o "$OUT/res.zip"

echo "[2/6] aapt2 link"
"$AAPT2" link -o "$OUT/base.apk" \
  -I "$JAR" \
  --manifest AndroidManifest.xml \
  --java "$OUT/gen" \
  --min-sdk-version 26 --target-sdk-version 34 \
  --version-code "$VERSION_CODE" --version-name "$VERSION_NAME" \
  "$OUT/res.zip"

# Build-time constants (kept out of git): the update/log server host.
mkdir -p "$OUT/gen/com/qudelixwidget/app"
cat > "$OUT/gen/com/qudelixwidget/app/BuildInfo.java" <<JAVA
package com.qudelixwidget.app;
/** Generated by build_apk.sh from local.env — do not edit. */
final class BuildInfo {
    private BuildInfo() {}
    static final String UPDATE_HOST = "${UPDATE_HOST:-}";
}
JAVA

echo "[3/6] javac"
find src "$OUT/gen" -name '*.java' > "$OUT/sources.txt"
# Must FAIL the build on compile errors (a past `|| true` here published an APK with no code).
if ! "$JAVAC" -source 8 -target 8 -nowarn -encoding UTF-8 \
  -classpath "$JAR" -d "$OUT/classes" @"$OUT/sources.txt" > "$OUT/javac.log" 2>&1; then
  grep -v 'bootstrap class path' "$OUT/javac.log"
  echo "javac FAILED — not building an APK"; exit 1
fi
grep -v 'bootstrap class path' "$OUT/javac.log" || true

echo "[4/6] d8 -> dex"
find "$OUT/classes" -name '*.class' > "$OUT/classes.txt"
"$D8" --min-api 26 --lib "$JAR" --output "$OUT/dex" @"$OUT/classes.txt"

echo "[5/6] assemble apk (insert classes.dex) + zipalign"
cp "$OUT/base.apk" "$OUT/unsigned.apk"
python3 -I - "$OUT/unsigned.apk" "$OUT/dex/classes.dex" <<'PY'
import sys, zipfile
apk, dex = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(apk, 'a', zipfile.ZIP_DEFLATED) as z:
    z.write(dex, 'classes.dex')
print("  classes.dex added")
PY
"$ZIPALIGN" -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

echo "[6/6] apksigner sign"
"$APKSIGNER" sign \
  --ks debug.keystore --ks-pass pass:android --key-pass pass:android \
  --ks-key-alias androiddebugkey \
  --out "$OUT/qudelix-widget.apk" "$OUT/aligned.apk"
"$APKSIGNER" verify --verbose "$OUT/qudelix-widget.apk" | head -5

echo "DONE -> $OUT/qudelix-widget.apk"
ls -la "$OUT/qudelix-widget.apk"
